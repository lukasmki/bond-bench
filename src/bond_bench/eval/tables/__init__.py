"""Tabulated assumptions shipped with the canonical methods.

- ``bond_windows.csv`` (A2): distance windows W_{ab k} per element pair and
  bond class (k ∈ {1, 1.5 aromatic, 2, 3}). Generated by
  ``scripts/fit_windows.py`` from the B2 calibration stratum.
- ``atom_penalties.csv`` (A3, ``atom_penalty`` preset of canonical O): atomic
  penalty scores AP(z, connectivity, context, valence), Wang et al. (2006),
  Table 2.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import polars as pl


TABLE_DIR = Path(__file__).parent
WINDOWS_CSV = TABLE_DIR / "bond_windows.csv"
PENALTIES_CSV = TABLE_DIR / "atom_penalties.csv"


@dataclass(frozen=True)
class Window:
    lo: float
    hi: float
    center: float
    count: int


@lru_cache(maxsize=None)
def bond_windows(path: Path = WINDOWS_CSV) -> dict[tuple[int, int, float], Window]:
    """{(z_a, z_b, k): Window} with z_a ≤ z_b."""
    if not path.exists():
        raise FileNotFoundError(f"{path} missing; run scripts/fit_windows.py")
    df = pl.read_csv(path)
    return {
        (int(r["z_a"]), int(r["z_b"]), float(r["k"])): Window(r["lo"], r["hi"], r["center"], int(r["count"]))
        for r in df.iter_rows(named=True)
    }


#: Penalty for a (row, valence) cell the source table leaves empty. Wang et al.
#: treat empty cells as disallowed; a large finite value keeps P4 feasible.
MISSING_PENALTY = 1000.0


@dataclass(frozen=True)
class PenaltyRow:
    no: int
    z: int
    connectivity: int | None  # None: any connectivity
    context: str | None  # None: the generic atom type
    scores: dict[int, float]  # valence -> penalty

    def penalty(self, valence: int) -> float:
        return self.scores.get(valence, MISSING_PENALTY)


@dataclass
class AtomPenalties:
    """Wang et al. (2006) atomic penalty scores, keyed by element, connectivity and context.

    Connectivity counts all bonded atoms, H included; valence is the sum of
    bond orders (H included). Charges do not enter the score.
    """

    rows: list[PenaltyRow]

    @property
    def elements(self) -> frozenset[int]:
        return frozenset(r.z for r in self.rows)

    def row(self, z: int, connectivity: int, contexts: set[str]) -> PenaltyRow | None:
        """Most specific matching row: context beats generic, explicit connectivity beats any."""
        best, best_rank = None, -1
        for r in self.rows:
            if r.z != z or (r.connectivity is not None and r.connectivity != connectivity):
                continue
            if r.context is not None and r.context not in contexts:
                continue
            rank = 2 * (r.context is not None) + (r.connectivity is not None)
            if rank > best_rank:
                best, best_rank = r, rank
        return best


@lru_cache(maxsize=None)
def atom_penalties(path: Path = PENALTIES_CSV) -> AtomPenalties:
    if not path.exists():
        raise FileNotFoundError(
            f"{path} missing: the atom_penalty preset needs the Wang et al. 2006 APS table "
            "(columns no, element, z, connectivity, context, valence, penalty)"
        )
    df = pl.read_csv(path, comment_prefix="#", schema_overrides={"context": pl.String})
    rows: dict[tuple, dict[int, float]] = {}
    meta: dict[tuple, int] = {}
    for r in df.iter_rows(named=True):
        context = r["context"] or None
        if context is not None and context not in KNOWN_CONTEXTS:
            raise ValueError(f"{path.name} row {r['no']}: no detector for context {context!r}")
        key = (int(r["z"]), r["connectivity"], context)
        rows.setdefault(key, {})[int(r["valence"])] = float(r["penalty"])
        meta[key] = int(r["no"])
    return AtomPenalties([
        PenaltyRow(meta[k], k[0], None if k[1] is None else int(k[1]), k[2], v) for k, v in rows.items()
    ])


#: Context qualifiers of the table, matched exactly; detectors live in methods/optimization.py.
KNOWN_CONTEXTS = frozenset({
    "in C≡N–R",
    "in COO−",
    "in N=N=R",
    "in nitro",
    "in pyridine-1-oxide, etc.",
    "in pyridine-1-thiol anion, etc.",
    "bonded to two O(X1) or S(X1)",
    "bonded to three O(X1) or S(X1)",
    "bonded to four O(X1) or S(X1)",
})
