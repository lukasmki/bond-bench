"""Tabulated assumptions shipped with the canonical methods.

- ``bond_windows.csv`` (A2): distance windows W_{ab k} per element pair and
  bond class (k ∈ {1, 1.5 aromatic, 2, 3}). Generated by
  ``scripts/fit_windows.py`` from the B2 calibration stratum.
- ``atom_penalties.csv`` (A3, ``atom_penalty`` preset of canonical O): atomic
  valence penalties AP(z, connectivity, valence) of Wang et al. (2006),
  transcribed from antechamber's APS.DAT. Not shipped yet.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import polars as pl

from ..core.elements import AtomState

TABLE_DIR = Path(__file__).parent
WINDOWS_CSV = TABLE_DIR / "bond_windows.csv"
PENALTIES_CSV = TABLE_DIR / "atom_penalties.csv"


@dataclass(frozen=True)
class Window:
    lo: float
    hi: float
    center: float
    count: int


@lru_cache(maxsize=None)
def bond_windows(path: Path = WINDOWS_CSV) -> dict[tuple[int, int, float], Window]:
    """{(z_a, z_b, k): Window} with z_a ≤ z_b."""
    if not path.exists():
        raise FileNotFoundError(f"{path} missing; run scripts/fit_windows.py")
    df = pl.read_csv(path)
    return {
        (int(r["z_a"]), int(r["z_b"]), float(r["k"])): Window(r["lo"], r["hi"], r["center"], int(r["count"]))
        for r in df.iter_rows(named=True)
    }


@lru_cache(maxsize=None)
def atom_penalty_fn(path: Path = PENALTIES_CSV) -> Callable[[int, int, AtomState], float]:
    """AP(z, connectivity, state); states absent from the table get ``default``."""
    if not path.exists():
        raise FileNotFoundError(
            f"{path} missing: the atom_penalty preset needs the Wang et al. 2006 APS table "
            "(columns z, connectivity, charge, valence, penalty)"
        )
    df = pl.read_csv(path, comment_prefix="#")
    table = {
        (int(r["z"]), int(r["connectivity"]), int(r["charge"]), int(r["valence"])): float(r["penalty"])
        for r in df.iter_rows(named=True)
    }
    default = 64.0

    def ap(z: int, connectivity: int, st: AtomState) -> float:
        return table.get((z, connectivity, st.charge, st.valence), default)

    return ap
